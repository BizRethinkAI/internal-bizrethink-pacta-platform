#!/usr/bin/env node
/**
 * Extract the live template contract from the records the funder's platform ships.
 *
 * The funder's platform prefills a published template by AcroForm WIDGET NAME
 * (`formValues`), not by Documenso field label. Those names are therefore an
 * interface this repository does not deploy and cannot rename unilaterally —
 * ADR 0023's parity obligation is about them.
 *
 * This writes `packages/bizrethink/mca/publish/live-template-contract.json`
 * from `lombard-platform/src/templates/*.published.json`. It is run by hand
 * when a template is republished there, NOT in CI: the source repository is a
 * sibling checkout, not a dependency, and the point of the vendored copy is
 * that the test keeps working without it.
 *
 *   node scripts/mca/extract-template-contract.mjs ~/github/lombard/lombard-platform
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

/**
 * The published record each MCA instrument is sent from today, and the name the
 * funder's platform calls it by.
 *
 * TWO OF OUR INSTRUMENTS SHARE ONE LIVE TEMPLATE. `equipment-lease` and
 * `subscription` are the twin `instruments.ts` describes — one clause published
 * in two documents — and the funder's platform resolves BOTH to template 120,
 * under the single kind `subscription` (`documenso-templates.ts` imports
 * `equipment-lease-v2d.published.json` for it and has no `equipment-lease` kind
 * at all). So the twin is one document in the send path and two in the library.
 * Recorded rather than reconciled: which it should be is a question for the
 * builder's first publication, and pinning it wrong would hide it.
 */
const RECORDS = {
  frpa: { file: 'frpa-v2d.published.json', platformKind: 'frpa' },
  'equipment-lease': { file: 'equipment-lease-v2d.published.json', platformKind: 'subscription' },
  subscription: { file: 'equipment-lease-v2d.published.json', platformKind: 'subscription' },
  'iso-pra': { file: 'isopra-v2c.published.json', platformKind: 'iso-pra' },
  'permission-to-release': { file: 'permission-to-release-v2b.published.json', platformKind: 'permission-to-release' },
  'split-funding': { file: 'payzli-v2b.published.json', platformKind: 'payzli' },
};

const root = process.argv[2];

if (!root) {
  console.error('usage: extract-template-contract.mjs <path to lombard-platform checkout>');
  process.exit(2);
}

const dir = join(root, 'src', 'templates');
const present = new Set(readdirSync(dir));
const instruments = {};

for (const [instrument, { file, platformKind }] of Object.entries(RECORDS)) {
  if (!present.has(file)) {
    console.error(`missing ${file} in ${dir} — has the template been republished under a new name?`);
    process.exit(1);
  }

  const record = JSON.parse(readFileSync(join(dir, file), 'utf8'));
  const widgets = [...(record.acroformFields ?? [])].sort();

  if (widgets.length === 0) {
    console.error(`${file} lists no acroformFields — nothing to pin`);
    process.exit(1);
  }

  instruments[instrument] = {
    source: file,
    platformKind,
    templateId: record.templateId,
    publishedAt: record.publishedAt,
    title: record.title,
    /**
     * Unique field names. `acroformFieldCount` is higher because a name may
     * carry several widgets — `merchant_legal_name` has three on the FRPA — and
     * one `formValues` entry fills all of them.
     */
    widgets,
    widgetAnnotations: record.acroformFieldCount ?? null,
    recipients: Object.entries(record.recipients ?? {})
      .map(([role, r]) => ({ role, signingOrder: r.signingOrder }))
      .sort((a, b) => a.signingOrder - b.signingOrder),
    signerFields: record.documensoFields ?? {},
  };
}

const out = join(
  process.cwd(),
  'packages/bizrethink/mca/publish/live-template-contract.json',
);

writeFileSync(
  out,
  `${JSON.stringify(
    {
      $comment:
        'GENERATED by scripts/mca/extract-template-contract.mjs from lombard-platform/src/templates. Do not hand-edit: re-extract when a template is republished, and let the diff be the review.',
      extractedAt: new Date().toISOString().slice(0, 10),
      instruments,
    },
    null,
    2,
  )}\n`,
);

console.log(`wrote ${out}`);
for (const [id, r] of Object.entries(instruments)) {
  console.log(`  ${id.padEnd(22)} template ${r.templateId}  ${r.widgets.length} names  ${r.recipients.length} recipients`);
}
